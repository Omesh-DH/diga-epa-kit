"""Rewrite docs/spec-inventory.md from the pinned packages (Phase 0 inventory).

Per MIO DiGA profile: canonical URL, base, mapper status, must-support
elements, required/extensible bindings and invariants. Bindings and
invariants are collected along the baseDefinition chain through kbv.basis
and de.basisprofil.r4, because the KBV packages ship differentials only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from diga_epa_kit.terminology.versions import DEFAULT_VERSION, get_pack  # noqa: E402

PACKAGES = ROOT / "spec" / "packages"
MIO = f"kbv.mio.diga#{DEFAULT_VERSION}"


def load() -> dict[str, tuple[str, dict]]:
    """url -> (package folder name, StructureDefinition) for every pinned package."""
    out: dict[str, tuple[str, dict]] = {}
    for folder in sorted(p for p in PACKAGES.iterdir() if p.is_dir()):
        for f in sorted((folder / "package").glob("*.json")):
            try:
                sd = json.loads(f.read_text(encoding="utf-8"))
            except ValueError:
                continue
            if sd.get("resourceType") == "StructureDefinition":
                out[sd["url"]] = (folder.name, sd)
    return out


def chain(sds: dict[str, tuple[str, dict]], url: str):
    """The profile and its bases, as far as the pinned packages go."""
    while url.split("|")[0] in sds:
        pkg, sd = sds[url.split("|")[0]]
        yield pkg, sd
        url = sd.get("baseDefinition", "")


def short(url: str) -> str:
    return url.rsplit("/", 1)[-1]


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def main() -> int:
    if not (PACKAGES / MIO).exists():
        print(f"{PACKAGES / MIO} missing; run scripts/fetch_spec.py", file=sys.stderr)
        return 2
    sds = load()
    mapped = {name: key for key, name in get_pack().profiles.items()}
    profiles = sorted(
        (sd for pkg, sd in sds.values() if pkg == MIO and sd.get("kind") == "resource"),
        key=lambda sd: sd["url"],
    )

    overview, bindings, invariants, must_support = [], [], [], []
    for sd in profiles:
        name = short(sd["url"])
        ms: list[str] = []
        n_bind = n_inv = 0
        for depth, (pkg, link) in enumerate(chain(sds, sd["url"])):
            for e in link.get("differential", {}).get("element", []):
                if depth == 0 and e.get("mustSupport"):
                    ms.append(e["id"])
                b = e.get("binding") or {}
                if b.get("strength") in ("required", "extensible") and b.get("valueSet"):
                    bindings.append((name, e["id"], b["strength"], short(b["valueSet"]), pkg))
                    n_bind += 1
                for c in e.get("constraint", []):
                    invariants.append((name, c["key"], c.get("severity", ""), c.get("expression", ""), pkg))
                    n_inv += 1
        base = short(sd.get("baseDefinition", ""))
        key = f"`{mapped[name]}`" if name in mapped else "–"
        overview.append((name, sd["type"], base, len(ms), n_bind, n_inv, key))
        must_support.append((name, ms))

    done = sum(1 for r in overview if r[-1] != "–")
    lines = [
        "# Spec inventory",
        "",
        f"Generated by `scripts/spec_inventory.py` from `{MIO}` and its pinned dependencies. Do not edit by hand.",
        f"{done} of {len(overview)} resource profiles mapped. Canonical URL of each profile: "
        "`https://fhir.kbv.de/StructureDefinition/<Profile>`.",
        "",
        "## Profiles",
        "",
        "| Profile | Type | Base | Must-support | Bindings (req/ext) | Invariants | Mapper key |",
        "| --- | --- | --- | --- | --- | --- | --- |",
        *(f"| {n} | {t} | {cell(b)} | {m} | {bi} | {i} | {k} |" for n, t, b, m, bi, i, k in overview),
        "",
        "## Required and extensible bindings",
        "",
        "Collected along the base chain; `Source` is the package that declares the binding.",
        "",
        "| Profile | Element | Strength | ValueSet | Source |",
        "| --- | --- | --- | --- | --- |",
        *(f"| {n} | `{cell(e)}` | {s} | {cell(v)} | {p} |" for n, e, s, v, p in bindings),
        "",
        "## Invariants",
        "",
        "| Profile | Key | Severity | FHIRPath | Source |",
        "| --- | --- | --- | --- | --- |",
        *(f"| {n} | {k} | {s} | `{cell(x)}` | {p} |" for n, k, s, x, p in invariants),
        "",
        "## Must-support elements",
        "",
        "Declared in the MIO DiGA differential (element ids).",
        "",
    ]
    for name, ms in must_support:
        lines += [f"### {name}", "", ", ".join(f"`{cell(m)}`" for m in ms) or "none", ""]

    (ROOT / "docs" / "spec-inventory.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{done}/{len(overview)} profiles mapped, {len(bindings)} bindings, {len(invariants)} invariants")
    return 0


if __name__ == "__main__":
    sys.exit(main())
