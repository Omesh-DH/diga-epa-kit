"""Rewrite docs/spec-inventory.md: every profile in the pinned MIO DiGA package and its mapper status."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from diga_epa_kit.terminology.versions import DEFAULT_VERSION, get_pack  # noqa: E402

PKG = ROOT / "spec" / "packages" / f"kbv.mio.diga#{DEFAULT_VERSION}" / "package"


def main() -> int:
    if not PKG.exists():
        print(f"{PKG} missing; run scripts/fetch_spec.py", file=sys.stderr)
        return 2
    mapped = {name: key for key, name in get_pack().profiles.items()}
    rows = []
    for f in sorted(PKG.glob("*.json")):
        sd = json.loads(f.read_text(encoding="utf-8"))
        if sd.get("resourceType") != "StructureDefinition" or sd.get("kind") != "resource":
            continue
        name = sd["url"].rsplit("/", 1)[-1]
        rows.append((name, sd["type"], f"`{mapped[name]}`" if name in mapped else "–"))

    done = sum(1 for r in rows if r[2] != "–")
    lines = [
        "# Spec inventory",
        "",
        f"Generated by `scripts/spec_inventory.py` from `kbv.mio.diga#{DEFAULT_VERSION}`. "
        f"{done} of {len(rows)} resource profiles mapped.",
        "",
        "| Profile | Type | Mapper key |",
        "| --- | --- | --- |",
        *(f"| {n} | {t} | {k} |" for n, t, k in rows),
        "",
    ]
    (ROOT / "docs" / "spec-inventory.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"{done}/{len(rows)} profiles mapped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
